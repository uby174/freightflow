import { eq } from "drizzle-orm";
import {
  db,
  carrierShipments,
  orders,
  parcels,
  pickupBookings,
  quotes,
  trackingEventsBranded,
  notifications,
} from "@/db";
import { PARCEL_PREFIX } from "./config";
import { getCarrier } from "./carrier/fake";
import { TEMPLATES } from "./sanitize";
import type { PriceQuote, QuoteItem } from "./pricing";

export interface CreateOrderInput {
  locale: "fr" | "en";
  mode: "dropoff" | "pickup";
  contents: string;
  lines: QuoteItem[]; // pinned resolved lines (catalog refs + custom boxes)
  quote: PriceQuote; // server-computed, from those lines
  classifySource: string; // ai | keyword | cache
  confidence: number;
  departureId: number;
  sender: {
    name: string;
    phone: string;
    email?: string;
    whatsapp: boolean;
    address?: string;
    postcode?: string;
    city?: string;
  };
  receiver: {
    name: string;
    phone: string;
    city: string;
    neighborhood?: string;
    landmark?: string;
  };
  pickupKm?: number;
}

function generateCode(): string {
  const year = new Date().getFullYear();
  for (let i = 0; i < 20; i++) {
    const n = Math.floor(100000 + Math.random() * 900000);
    const code = `${PARCEL_PREFIX}-${year}-${n}`;
    const clash = db
      .select({ id: orders.id })
      .from(orders)
      .where(eq(orders.code, code))
      .get();
    if (!clash) return code;
  }
  throw new Error("could not allocate parcel number");
}

export async function createOrder(input: CreateOrderInput) {
  const code = generateCode();
  const now = new Date();
  const q = input.quote;

  // Aggregate parcel record: representative cube from chargeable volume,
  // dominant cargo class, catalog-nominal weight (the reconciliation baseline).
  const side = Math.max(
    20,
    Math.round(Math.cbrt(Math.max(q.chargeableM3, 0.001)) * 100)
  );
  const dominant =
    q.lines.slice().sort((a, b) => b.volumeM3 - a.volumeM3)[0]?.itemClass ??
    "parcel";
  const fragile = q.lines.some(
    (l) => l.itemClass === "tv" || l.itemClass === "appliance_large"
  );

  const order = db
    .insert(orders)
    .values({
      code,
      status: "booked",
      mode: input.mode,
      locale: input.locale,
      senderName: input.sender.name,
      senderPhone: input.sender.phone,
      senderEmail: input.sender.email ?? null,
      senderWhatsapp: input.sender.whatsapp,
      receiverName: input.receiver.name,
      receiverPhone: input.receiver.phone,
      receiverCity: input.receiver.city,
      receiverNeighborhood: input.receiver.neighborhood ?? null,
      receiverLandmark: input.receiver.landmark ?? null,
      contents: input.contents,
      linesJson: JSON.stringify(input.lines),
      departureId: input.departureId,
      packagingCents: 0,
      shippingCents: q.goodsCents,
      pickupCents: q.pickupCents,
      totalCents: q.totalCents,
      createdAt: now,
    })
    .returning()
    .get();

  db.insert(parcels)
    .values({
      orderId: order.id,
      estWeightKg: q.totalWeightKg,
      estL: side,
      estW: side,
      estH: side,
      packagingType: dominant,
      fragile,
      confidence: input.confidence,
      estimatedBy: input.classifySource,
    })
    .run();

  db.insert(quotes)
    .values({
      orderId: order.id,
      version: 1,
      packagingCents: 0,
      shippingCents: q.goodsCents,
      pickupCents: q.pickupCents,
      totalCents: q.totalCents,
      distanceKm: input.pickupKm ?? null,
      distanceSource: input.pickupKm !== undefined ? "api" : null,
      reason: "initial",
      createdAt: now,
    })
    .run();

  if (input.mode === "pickup" && input.sender.address) {
    db.insert(pickupBookings)
      .values({
        orderId: order.id,
        address: input.sender.address,
        postcode: input.sender.postcode ?? "",
        city: input.sender.city ?? "",
        distanceKm: input.pickupKm ?? 0,
        status: "pending",
      })
      .run();
  }

  // Book with the (hidden) carrier — mapping lives only in internal tables
  const carrier = getCarrier();
  const shipment = await carrier.createShipment(order.id);
  db.insert(carrierShipments)
    .values({
      orderId: order.id,
      carrierName: carrier.name,
      carrierTrackingNumber: shipment.carrierTrackingNumber,
      plannedEvents: JSON.stringify(shipment.plannedEvents),
      startedAt: now,
    })
    .run();

  // First branded milestone: booked (generated by us, not the carrier)
  const t = TEMPLATES.booked;
  const branded = db
    .insert(trackingEventsBranded)
    .values({
      orderId: order.id,
      rawId: null,
      statusKey: "booked",
      messageFr: t.fr,
      messageEn: t.en,
      generatedBy: "template",
      occurredAt: now,
    })
    .returning({ id: trackingEventsBranded.id })
    .get();
  db.insert(notifications)
    .values({
      orderId: order.id,
      brandedId: branded.id,
      channel: input.sender.whatsapp ? "whatsapp" : "email",
      locale: input.locale,
      status: "sent",
      sentAt: now,
    })
    .run();

  return order;
}
